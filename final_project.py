def build_model(trainable_base=False, fine_tune_at=None):
    """
    trainable_base=False  → freeze entire backbone (fast)
    trainable_base=True   → unfreeze entire backbone
    fine_tune_at=100      → freeze layers before layer 100, train the rest (recommended)
    """
    inputs = keras.Input(shape=(IMG_SIZE, IMG_SIZE, 3))  # model expects [0, 1]

    # Convert [0,1] → [0,255] and apply official ResNet50 preprocessing
    x = layers.Rescaling(255.0)(inputs)
    x = tf.keras.applications.resnet50.preprocess_input(x)

    base = ResNet50(
        weights="imagenet",
        include_top=False,
        input_tensor=x
    )

    if fine_tune_at is not None:
        # Freeze early layers, unfreeze from fine_tune_at onwards
        for layer in base.layers[:fine_tune_at]:
            layer.trainable = False
        for layer in base.layers[fine_tune_at:]:
            layer.trainable = True
    else:
        base.trainable = trainable_base

    x = layers.GlobalAveragePooling2D()(base.output)
    x = layers.Dropout(0.5)(x)
    outputs = layers.Dense(NUM_CLASSES, activation="softmax")(x)

    model = models.Model(inputs, outputs)
    return model

