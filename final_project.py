# 5. FGSM ATTACK
# ============================================================
# Single-step white-box attack (Goodfellow et al., 2015).
# Operates in the [0,1] image domain, same as PGD and the Gaussian noise.

@tf.function
def fgsm_attack(model, images, labels, eps=EPS):
    with tf.GradientTape() as tape:
        tape.watch(images)
        preds = model(images, training=False)
        loss = tf.keras.losses.categorical_crossentropy(labels, preds)
    grads = tape.gradient(loss, images)
    adv = images + eps * tf.sign(grads)
    adv = tf.clip_by_value(adv, 0.0, 1.0)
    return adv

