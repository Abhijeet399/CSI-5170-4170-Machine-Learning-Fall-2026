# VRAM HELPER
# ----------------------------------------------------------------------
# TensorFlow keeps a model's weights, optimizer state, and graph on the GPU
# as long as ANY Python reference survives. Rebinding a variable is not
# enough -- a Keras History object, for instance, keeps a hidden reference to
# its model. free_memory() drops the named globals, clears the TF/Keras graph,
# and runs garbage collection so the next model has room.
#
# NOTE: clear_session() invalidates EVERY model built earlier in this kernel,
# so only free once you are done with those models. Each training/eval section
# below rebuilds or reloads its model from disk, so freeing at the end of a
# section is always safe.
#
# nvidia-smi may still show a large reserved block afterwards: that is TF's
# memory pool, reused internally rather than returned to the OS. Only a kernel
# restart returns VRAM to zero.
# ======================================================================
import gc

def free_memory(*names):
    """Delete the named globals, clear the TF/Keras graph, collect garbage."""
    g = globals()
    for n in names:
        g.pop(n, None)
    try:
        tf.keras.backend.clear_session()
    except Exception:
        try:
            import keras
            keras.backend.clear_session()
        except Exception:
            pass
    gc.collect()
    dropped = ", ".join(names) if names else "(session only)"
    print(f"[free_memory] cleared TF session + GC; dropped: {dropped}")

