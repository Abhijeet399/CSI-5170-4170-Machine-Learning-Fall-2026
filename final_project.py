@tf.function
def pgd_attack(model, images, labels, eps=EPS, alpha=PGD_STEP_SIZE, steps=PGD_STEPS):
    adv_images = images + tf.random.uniform(tf.shape(images), -eps, eps)
    adv_images = tf.clip_by_value(adv_images, 0.0, 1.0)

    for _ in range(steps):
        with tf.GradientTape() as tape:
            tape.watch(adv_images)
            preds = model(adv_images, training=False)
            loss = tf.keras.losses.categorical_crossentropy(labels, preds)

        gradients = tape.gradient(loss, adv_images)
        adv_images = adv_images + alpha * tf.sign(gradients)
        # Project onto epsilon ball
        adv_images = tf.clip_by_value(adv_images, images - eps, images + eps)
        adv_images = tf.clip_by_value(adv_images, 0.0, 1.0)

    return adv_images

@tf.function
def train_step(model, images, labels, optimizer):
    # Generate adversarial examples
    adv_images = pgd_attack(model, images, labels)

    with tf.GradientTape() as tape:
        # Clean predictions
        clean_preds = model(images, training=True)
        loss_clean = tf.keras.losses.categorical_crossentropy(labels, clean_preds)

        # Adversarial predictions
        adv_preds = model(adv_images, training=True)
        loss_adv = tf.keras.losses.categorical_crossentropy(labels, adv_preds)

        # Combined loss
        loss = (1.0 - ADV_RATIO) * loss_clean + ADV_RATIO * loss_adv
        loss = tf.reduce_mean(loss)

    gradients = tape.gradient(loss, model.trainable_variables)
    optimizer.apply_gradients(zip(gradients, model.trainable_variables))

    # Metrics
    clean_acc = tf.reduce_mean(tf.keras.metrics.categorical_accuracy(labels, clean_preds))
    adv_acc = tf.reduce_mean(tf.keras.metrics.categorical_accuracy(labels, adv_preds))

    return loss, clean_acc, adv_acc

def adversarial_train(model, train_gen, val_gen, epochs=EPOCHS):
    history = {
        "loss": [], "clean_acc": [], "adv_acc": [],
        "val_loss": [], "val_acc": []
    }

    best_val_acc = 0.0
    steps_per_epoch = len(train_gen)

    for epoch in range(epochs):
        print(f"\n=== Epoch {epoch+1}/{epochs} ===")
        epoch_loss = []
        epoch_clean_acc = []
        epoch_adv_acc = []

        # Training
        pbar = tqdm(range(steps_per_epoch), desc="Training")
        for step in pbar:
            images, labels = next(train_gen)
            images = tf.convert_to_tensor(images, dtype=tf.float32)
            labels = tf.convert_to_tensor(labels, dtype=tf.float32)

            loss, clean_acc, adv_acc = train_step(model, images, labels, optimizer)

            epoch_loss.append(loss.numpy())
            epoch_clean_acc.append(clean_acc.numpy())
            epoch_adv_acc.append(adv_acc.numpy())

            pbar.set_postfix({
                "loss": f"{np.mean(epoch_loss):.4f}",
                "clean_acc": f"{np.mean(epoch_clean_acc):.4f}",
                "adv_acc": f"{np.mean(epoch_adv_acc):.4f}"
            })

        # Validation (on clean data)
        val_loss, val_acc = model.evaluate(val_gen, verbose=0)

        # Record history
        history["loss"].append(np.mean(epoch_loss))
        history["clean_acc"].append(np.mean(epoch_clean_acc))
        history["adv_acc"].append(np.mean(epoch_adv_acc))
        history["val_loss"].append(val_loss)
        history["val_acc"].append(val_acc)

        print(f"Val Loss: {val_loss:.4f} | Val Acc: {val_acc:.4f}")

        # Save best model
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            model.save_weights(MODEL_SAVE_PATH)
            print(f"  → Best model saved (Val Acc = {val_acc:.4f})")

    return history

