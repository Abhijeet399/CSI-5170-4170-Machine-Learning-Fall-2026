"""## 8. Explainability — Grad-CAM & Score-CAM
Both return a normalized heatmap at the last conv resolution (`conv5_block3_out` for ResNet50), computed directly on `[0,1]` inputs.
"""

# ============================================================
# 8. EXPLAINABILITY:  Grad-CAM  &  Score-CAM
# ============================================================
# Both return a [0,1] heatmap at the last conv feature-map resolution.
# The model ingests [0,1] images and preprocesses internally, so CAMs are
# computed directly on [0,1] inputs — no extra preprocessing needed here.

import matplotlib.cm as cm

def get_last_conv_layer_name(model):
    """Last layer with a 4D (spatial) output — conv5_block3_out for ResNet50."""
    for layer in reversed(model.layers):
        try:
            if len(layer.output.shape) == 4:
                return layer.name
        except Exception:
            continue
    raise ValueError("No 4D convolutional layer found.")

def compute_gradcam(model, image, class_index=None, last_conv=None):
    """Gradient-based CAM (Selvaraju et al., 2017). image: (H,W,3) in [0,1]."""
    if last_conv is None:
        last_conv = get_last_conv_layer_name(model)
    grad_model = models.Model(model.inputs,
                              [model.get_layer(last_conv).output, model.output])
    img = tf.convert_to_tensor(image[None], tf.float32)
    with tf.GradientTape() as tape:
        conv_out, preds = grad_model(img, training=False)
        if class_index is None:
            class_index = int(tf.argmax(preds[0]))
        channel = preds[:, class_index]
    grads = tape.gradient(channel, conv_out)
    pooled = tf.reduce_mean(grads, axis=(0, 1, 2))
    cam = tf.reduce_sum(conv_out[0] * pooled, axis=-1)
    cam = tf.maximum(cam, 0)
    cam = cam / (tf.reduce_max(cam) + 1e-8)
    return cam.numpy(), class_index

def compute_scorecam(model, image, class_index=None, last_conv=None,
                     top_k=256, batch_size=64):
    """Gradient-free CAM (Wang et al., 2020). top_k caps channels for tractability
    (ResNet50 has 2048; full Score-CAM = 2048 forward passes per image)."""
    if last_conv is None:
        last_conv = get_last_conv_layer_name(model)
    conv_model = models.Model(model.inputs, model.get_layer(last_conv).output)
    img = image[None].astype(np.float32)
    acts = conv_model(tf.convert_to_tensor(img), training=False).numpy()[0]  # (h,w,C)
    H, W = image.shape[:2]
    acts_up = tf.image.resize(acts[None], (H, W)).numpy()[0]                 # (H,W,C)
    C = acts_up.shape[-1]
    if class_index is None:
        class_index = int(np.argmax(
            model(tf.convert_to_tensor(img), training=False).numpy()[0]))
    # keep the most energetic channels
    if top_k is not None and top_k < C:
        chans = np.argsort(acts_up.reshape(-1, C).max(0))[-top_k:]
    else:
        chans = np.arange(C)
    maps, masked = [], []
    for c in chans:
        m = acts_up[..., c]
        rng = m.max() - m.min()
        if rng < 1e-8:
            continue
        mn = (m - m.min()) / rng
        maps.append(mn)
        masked.append(image * mn[..., None])
    maps, masked = np.array(maps, np.float32), np.array(masked, np.float32)
    scores = []
    for i in range(0, len(masked), batch_size):
        p = model(tf.convert_to_tensor(masked[i:i+batch_size]), training=False).numpy()
        scores.append(p[:, class_index])
    weights = tf.nn.softmax(np.concatenate(scores)).numpy()
    cam = np.tensordot(weights, maps, axes=(0, 0))
    cam = np.maximum(cam, 0)
    cam = cam / (cam.max() + 1e-8)
    return cam, class_index

def overlay_cam(image, cam, alpha=0.45):
    cam_rs = tf.image.resize(cam[..., None], image.shape[:2]).numpy().squeeze()
    heat = cm.get_cmap("jet")(cam_rs)[..., :3]
    return np.clip((1 - alpha) * image + alpha * heat, 0, 1)

