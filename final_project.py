"""## 10. Explanation Faithfulness & Stability
Average Drop %, Increase in Confidence %, and heatmap stability under mild noise — quantifying *whether* the explanations are trustworthy, answering the third research question.
"""

# ============================================================
# 10. EXPLANATION FAITHFULNESS & STABILITY  (answers research Q3)
# ============================================================
# Faithfulness (Grad-CAM++ / Score-CAM protocol):
#   Average Drop %        = mean( max(0, Yc - Oc) / Yc ) * 100   (lower = better)
#   Increase in Conf. %   = mean( 1[Oc > Yc] ) * 100             (higher = better)
#   where Yc = confidence on the image, Oc = confidence on image * heatmap.
# Stability: correlation between the heatmap on a clean image and on the same
#   image with mild Gaussian noise (higher = more stable).

def explanation_metrics(model, val_gen, cam_fn=compute_gradcam,
                        n_images=40, stab_sigma=0.05):
    imgs, lbls = collect_images(val_gen, n_images)
    drops, incs, stabs = [], [], []
    for k in tqdm(range(len(imgs)), desc="faithfulness", leave=False):
        img = imgs[k]
        base = model(tf.convert_to_tensor(img[None], tf.float32),
                     training=False).numpy()[0]
        c = int(np.argmax(base)); Yc = float(base[c])
        cam, _ = cam_fn(model, img, class_index=c)
        cam_rs = tf.image.resize(cam[..., None], img.shape[:2]).numpy().squeeze()
        masked = img * cam_rs[..., None]
        Oc = float(model(tf.convert_to_tensor(masked[None], tf.float32),
                         training=False).numpy()[0][c])
        drops.append(max(0.0, Yc - Oc) / (Yc + 1e-8))
        incs.append(1.0 if Oc > Yc else 0.0)
        noisy = add_gaussian_noise_batch(img[None], stab_sigma)[0]
        cam_n, _ = cam_fn(model, noisy, class_index=c)
        stabs.append(np.corrcoef(cam.flatten(), cam_n.flatten())[0, 1])
    return {
        "avg_drop_%":              100 * float(np.mean(drops)),
        "increase_in_confidence_%": 100 * float(np.mean(incs)),
        "stability_corr":          float(np.nanmean(stabs)),
    }

