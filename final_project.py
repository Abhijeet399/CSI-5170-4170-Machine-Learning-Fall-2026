"""## 7. Input Denoising Defense
Cheap test-time preprocessing (Gaussian / median smoothing) applied to attacked inputs, to see how much accuracy a denoiser recovers under PGD.
"""

# ============================================================
# 7. INPUT DENOISING DEFENSE (test-time preprocessing)
# ============================================================
# Simple, model-agnostic defense: smooth the (possibly attacked) input before
# classifying. Measures how much a cheap denoiser recovers accuracy under PGD.

from scipy.ndimage import gaussian_filter, median_filter

def denoise_batch(images, method="gaussian", param=1.0):
    """images in [0,1], shape (N,H,W,3). method: 'gaussian' (sigma) or 'median' (window)."""
    out = np.empty_like(images, dtype=np.float32)
    for i in range(images.shape[0]):
        for c in range(images.shape[-1]):
            if method == "gaussian":
                out[i, ..., c] = gaussian_filter(images[i, ..., c], sigma=param)
            elif method == "median":
                out[i, ..., c] = median_filter(images[i, ..., c], size=int(param))
            else:
                out[i, ..., c] = images[i, ..., c]
    return np.clip(out, 0.0, 1.0)

def make_pgd_then_denoise_transform(model, method="gaussian", param=1.0, **pgd_kwargs):
    pgd_t = make_pgd_transform(model, **pgd_kwargs)
    def _t(images, labels):
        adv = _to_np(pgd_t(images, labels))
        return denoise_batch(adv, method, param)
    return _t

# ---------- Evaluate denoising defense (PGD, with vs without denoiser) ----------
DENOISE_METHOD = "gaussian"   # "gaussian" or "median"
DENOISE_PARAM  = 1.0          # sigma for gaussian; window size for median

denoise_rows = {}
for name, path in MODEL_PATHS.items():
    if not os.path.exists(path):
        continue
    m = load_for_eval(path)
    pgd_only = measure_accuracy(m, val_gen, make_pgd_transform(m),
                                EVAL_BATCHES, f"{name}:pgd")
    pgd_den  = measure_accuracy(
        m, val_gen,
        make_pgd_then_denoise_transform(m, method=DENOISE_METHOD, param=DENOISE_PARAM),
        EVAL_BATCHES, f"{name}:pgd+denoise")
    denoise_rows[name] = {"pgd": pgd_only, "pgd+denoise": pgd_den,
                          "recovered": pgd_den - pgd_only}
    del m

denoise_df = pd.DataFrame(denoise_rows).T
denoise_df.to_csv("results/denoising_defense.csv")
print(f"\n===== DENOISING DEFENSE ({DENOISE_METHOD}, param={DENOISE_PARAM}) =====")
print(denoise_df.round(4))

