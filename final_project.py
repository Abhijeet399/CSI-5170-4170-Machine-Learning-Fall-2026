def add_gaussian_noise_batch(images, sigma, max_val=1.0):
    """
    images: numpy array in [0, max_val]
    sigma: standard deviation relative to max_val
    """
    noise = np.random.normal(0, sigma * max_val, images.shape).astype(np.float32)
    noisy = np.clip(images + noise, 0.0, max_val)
    return noisy


def evaluate_under_noise(model, val_gen, noise_levels=[0.05, 0.10, 0.15, 0.20]):
    print("\n" + "="*60)
    print("Evaluating under Gaussian Noise")
    print("="*60)

    results = {}

    # Clean accuracy
    eval_results = model.evaluate(val_gen, verbose=0)
    acc = eval_results[1]          # accuracy is always the second value
    results["clean"] = acc
    print(f"Clean Accuracy: {acc:.4f}")

    results["clean"] = acc
    print(f"Clean Accuracy: {acc:.4f}")

    for sigma in noise_levels:
        print(f"\nTesting sigma = {sigma} ...")
        correct = 0
        total = 0

        for i in range(len(val_gen)):
            images, labels = val_gen[i]
            noisy_images = add_gaussian_noise_batch(images, sigma)
            preds = model.predict(noisy_images, verbose=0)
            correct += np.sum(np.argmax(preds, axis=1) == np.argmax(labels, axis=1))
            total += len(labels)

        acc = correct / total
        results[f"noise_{sigma}"] = acc
        print(f"Accuracy under σ={sigma}: {acc:.4f}")

    return results

